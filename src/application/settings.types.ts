/** Настройки, нужные прикладному слою (подмножество полной конфигурации). */
export interface OrchSettings {
	/** каталог состояния */
	home: string
	/** автоподтверждение прав агентов */
	autoApprove: boolean
	/** защита от зацикливания межагентной переписки */
	maxHops: number
	rateLimitPerMinute: number
	/** путь к CLI для вводной агентов */
	cliPath: string
	/** сколько ждать подтверждения отмены хода от nessy, прежде чем продолжить без него (мс, по умолчанию 3000) */
	cancelGraceMs?: number
	/** сколько заранее созданных сессий nessy держать про запас на пространство (0 — выключено; по умолчанию в конфиге 2) */
	warmSessions?: number
	/** через сколько мс простоя агента закрыть его сессию nessy (она поднимается снова при следующем сообщении; 0 — не закрывать; по умолчанию 120000) */
	idleCloseMs?: number
	/** включена проверка токенов: агентам в вводную добавляется ключ (`--key`) для команд от своего имени */
	authRequired?: boolean
	/** глубина порождения: агент оператора — 0, запущенный им — 1, … Глубже — отказ (по умолчанию 2) */
	maxDepth?: number
	/** сколько агентов сессии могут работать одновременно (по умолчанию 12) */
	maxActivePerSession?: number
	/** сколько агентов может быть в сессии всего, включая завершённые (по умолчанию 40) */
	maxAgentsPerSession?: number
	/** через сколько мс простоя завершённого (архивного) агента удалять автоматически (0 — не удалять; по умолчанию 6 часов) */
	agentTtlMs?: number
}
