export const HELP = `nessy-orch — оркестратор агентов nessy

СЕССИИ (одна сессия на весь разговор Claude: все его агенты работают в ней, у сессии свой inbox, источники и счётчики;
        несколько Claude работают параллельно, каждый в своей сессии)
  session new "<заголовок>" [--owner X] [--id slug]
                       завести сессию ОДИН РАЗ в начале: печатает id и ссылку nessy-orch://session/<id> для приложения
  session ls [--all]      сессии (по умолчанию активные)      session show <id>   агенты, план x/y, источники, токены
  session sources <id>    ссылки и источники, собранные за сессию
  session done <id> [--summary "…" | --summary-file F]      завершить сессию с итогом
  session reopen <id>     снова сделать активной             session rm <id>     удалить (агенты останутся вне сессий)

АГЕНТЫ
  spawn [--session S] [--name N] [--role R] [--wait] [--timeout СЕК] ["задача"]
                       создать агента (и сразу отправить задачу) В КАТАЛОГЕ ОРКЕСТРАТОРА (где идёт чат Claude); --space P — другой
                       каталог. --session — в сессии S (агент, запущенный агентом, наследует сессию родителя); --wait — дождаться
                       ответа; --role — роль (её инструкции попадут во вводную; имя по умолчанию = id роли)
  spawn-many [--session S] "имя|роль|поручение" "имя2||поручение2" …   несколько агентов ОДНИМ вызовом (быстрее, чем по одному).
                       Без heredoc: каждый аргумент — одно «имя|роль|поручение» (роль можно пропустить). Запасные способы:
                       --file <файл> (блоки «@@ имя role=роль» + текст поручения, либо JSON-массив) и --stdin
  send <агент|you> "текст" [--wait] [--queue] [--timeout СЕК] [--from ID]
                       отправить сообщение. СВОБОДНОГО агента оно запускает в работу (ответ придёт в inbox); работающий прерывается
                       и получает его первым; --queue — не прерывать, встать в очередь. --from — от имени агента (для самих агентов)
  ask <путь|space> "задача" [--session S]   короткий путь: spawn --wait
  ls [--all] [--session S]   агенты (выполнившие задачу — в архиве, их показывает --all); --session — только агенты сессии S
  show <агент>         последние события (подробно; обычно не нужен — ответы приходят в inbox)   watch <агент>   живой чат с агентом
  plan <агент>         план агента (чек-лист); агент публикует свой: plan --from <id> "- [x] …" "- [~] …" "- [ ] …"
                       (список целиком; [x] сделано, [~] в работе, [ ] впереди), --clear — убрать
  cancel <агент>       прервать ход                 kill <агент>    удалить агента
  archive <агент>      убрать в архив               restore <агент> вернуть из архива
                       (любое сообщение агенту в архиве будит его с прежним контекстом)

РОЛИ
  role ls              role show <id>               role rm <id>
  role add <имя> --instructions "…" | --file <путь> [--description D] [--id ID] [--color 0..360]
  role import [путь] [--force] [--dry-run]   загрузить роли из markdown-файлов (файл или папка;
                       по умолчанию — готовые роли из roles/). Существующие пропускаются, --force — перезаписать
  role export <id> [--out файл]               роль как markdown-файл (формат roles/README.md)

ЛЕНТА И ВХОДЯЩИЕ
  feed [-n 30] [--follow]   общая лента сообщений
  inbox [--session S] [--wait СЕК] [--peek]   новые ответы агентов вам (курсор сохраняется);
                       --session — только ответы агентов сессии S, со своим курсором на сессию.
                       --wait ждёт, только пока в сессии кто-то работает: агентов нет → сразу выход с кодом 4 (не зависает);
                       код 3 — таймаут, агенты ещё работают (запустить снова); 0 — ответы получены

ПРОСТРАНСТВА
  space add <путь> [--name N] [--url URL]    space ls    space rm <имя> [--force]

ХУКИ CLAUDE CODE (их задаёт плагин nessy; работают в терминале приложения — нужна NESSY_ORCH_TERMINAL)
  hook start|prompt|stop|end   подмешивает в контекст Claude сводку агентов и новые ответы (stdin — JSON события хука)

ПРИЛОЖЕНИЕ
  .  |  app [папка]    открыть приложение TClaude-Orch с терминалом в этой папке (nessy-orch . — из текущей, nessy-orch ~/proj)

СЛУЖЕБНОЕ
  status               состояние оркестратора
  install [--print]    установить launchd-сервис  uninstall

ОБЩИЕ ФЛАГИ: --json (машинный вывод), --help
Переменные: ORCH_PORT (по умолчанию 4337), NESSY_ORCH_SESSION (--session по умолчанию для spawn/ask/ls/inbox), NO_COLOR`
