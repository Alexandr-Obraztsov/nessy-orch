export const HELP = `nessy-orch — оркестратор агентов nessy

СЕССИИ (вкладка приложения = одна сессия: агенты, источники и счётчики; несколько Claude работают параллельно, каждый в своей)
  session new "<заголовок>" [--owner X] [--id slug]
                       вне приложения: завести сессию ОДИН РАЗ в начале (печатает id и ссылку nessy-orch://session/<id>)
  session ls [--all]      сессии (по умолчанию активные)      session show <id>   агенты, план x/y, источники, токены
  session sources <id>    ссылки и файлы, собранные за сессию
  session done <id> [--summary "…" | --summary-file F]      завершить сессию с итогом
  session reopen <id>     снова сделать активной             session rm <id>     удалить (агенты останутся вне сессий)

АГЕНТЫ  (spawn и send ЖДУТ результат сами: запускайте их в фоне — Bash с run_in_background: завершение разбудит вас; один агент = одна команда)
  spawn [--session S] [--name N] [--title "заголовок"] [--role R] [--no-wait] [--timeout СЕК] "задача"
                       создать агента и отправить задачу В КАТАЛОГЕ ОРКЕСТРАТОРА (где идёт чат Claude); --space P — другой каталог.
                       Команда ждёт ответ и печатает его (код 3 — не дождались, агент ещё работает: wait). --no-wait — вернуться сразу.
                       --name — техническое имя (занятое получит суффикс -2, -3; настоящее печатается сразу после создания), по нему потом «send <имя>»; --title — короткий
                       понятный заголовок для человека (до 80 знаков; цель — это само поручение); --role — роль (её инструкции попадут во вводную)
  send <агент|you> "текст" [--no-wait] [--interrupt] [--timeout СЕК] [--from ID]
                       отправить сообщение и дождаться ответа. СВОБОДНОГО агента оно запускает в работу, РАБОТАЮЩЕГО не прерывает:
                       уходит в идущий ход (агент увидит его между шагами), иначе встаёт в очередь; --interrupt — прервать.
                       --from — от имени агента (для самих агентов; агент по умолчанию не ждёт, ответ придёт ему сообщением, --wait — ждать)
  wait <агент> [--timeout СЕК]   дождаться, пока агент освободится, и вывести его последний ответ (код 3 — ещё работает)
  ask <путь|space> "задача" [--session S]   короткий путь: spawn в другом каталоге
  ls [--all] [--session S]   агенты и заполнение их контекста (выполнившие задачу — в архиве, их показывает --all)
  show <агент>         последние события (подробно; обычно не нужен)   watch <агент>   живой чат с агентом
  plan <агент>         план агента (чек-лист); агент публикует свой: plan --from <id> "- [x] …" "- [~] …" "- [ ] …"
                       (список целиком; [x] сделано, [~] в работе, [ ] впереди), --clear — убрать
  cancel <агент>       прервать ход                 kill <агент>    удалить агента
  archive <агент>      убрать в архив               restore <агент> вернуть из архива
                       (любое сообщение агенту в архиве будит его с прежним контекстом)

РОЛИ
  role ls              role show <id>               role rm <id>
  role add <имя> --instructions "…" | --file <путь> [--description D] [--id ID] [--color 0..360]
  role import [путь] [--force] [--dry-run]   загрузить роли из markdown-файлов (файл или папка;
                       по умолчанию — готовые роли из roles/). Существующие пропускаются, --force — перезаписать
  role export <id> [--out файл]               роль как markdown-файл (формат roles/README.md)

ЛЕНТА
  feed [-n 30] [--follow]   общая лента сообщений

ПРОСТРАНСТВА
  space add <путь> [--name N] [--url URL]    space ls    space rm <имя> [--force]

ФОНОВОЕ ОБУЧЕНИЕ (оркестратор сам собирает кейсы из сессий; настройки — ~/.nessy-orch/learning.json)
  learn [status]       настройки, очередь заданий, кейсы       learn on | off [--session S]   включить/выключить (в целом или для сессии)
  learn run [--session S]   собрать описание сейчас (сессии или кейса; без --session — все открытые кейсы)
  case ls              кейсы        case show <id>   шапка и summary.md        case rm <id>   удалить кейс
  case rebuild <id>    пересобрать описание заново      case note <id> "<текст>"   заметки пользователя кейса
  case read <id> [--max-chars N]   следующий блок событий кейса (агент-сборщик; в stderr — прогресс или done)
  case draft <id> [--file F] [--from A --key K]   сохранить черновик описания (иначе stdin)
  playbook ls | show <id>    плейбуки, которые обучение собрало из кейсов (статусы: draft, review, trial, active, disabled, archived)
  playbook review <id>       запустить авто-ревью            playbook approve <id> | reject <id> [--reason R]   ручное решение
  playbook revert <id> --version N   откат к версии (новой версией)      playbook rm <id>   удалить      playbook note <id> "<текст>"   заметки
  playbook edits <id>        правки улучшателя, ждущие решения (авто-ревью выключено)      playbook accept <id> <hash> | reject <id> <hash>   принять / отклонить правку
  learn journal [--limit N] [--revert <id>]   журнал автоматических решений и откат одной команды

ПРИЛОЖЕНИЕ
  .  |  app [папка]    открыть приложение TClaude-Orch с терминалом в этой папке (nessy-orch . — из текущей, nessy-orch ~/proj)

СЛУЖЕБНОЕ
  status               состояние оркестратора
  open [<id сессии>]   открыть сессию в приложении TClaude-Orch
  install [--print] [--ensure]   установить launchd-сервис (сервер копируется в ~/.nessy-orch/runtime; --ensure — только если нужно)  uninstall

ОБЩИЕ ФЛАГИ: --json (машинный вывод), --help
Переменные: ORCH_PORT (по умолчанию 4337), NESSY_ORCH_SESSION (--session по умолчанию для spawn/ask/ls), NO_COLOR`
